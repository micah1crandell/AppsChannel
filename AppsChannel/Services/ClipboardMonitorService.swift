import Foundation
import AppKit
import Combine
import SwiftUI

@MainActor
public final class ClipboardMonitorService: ObservableObject {
    public static let shared = ClipboardMonitorService()

    @Published public var items: [ClipboardItem] = [] {
        didSet {
            scheduleSave()
        }
    }

    @Published public var isPaused: Bool = false {
        didSet {
            UserDefaults.standard.set(isPaused, forKey: pausedKey)
        }
    }

    @Published public var excludeSensitive: Bool = false {
        didSet {
            UserDefaults.standard.set(excludeSensitive, forKey: excludeSensitiveKey)
        }
    }

    @Published public var retentionDuration: ClipboardRetentionDuration = .week {
        didSet {
            UserDefaults.standard.set(retentionDuration.rawValue, forKey: retentionKey)
            pruneAndSave()
        }
    }

    @Published public var maxItemsCount: Int = 500 {
        didSet {
            UserDefaults.standard.set(maxItemsCount, forKey: maxItemsKey)
            pruneAndSave()
        }
    }

    /// Stores the external application that was active before AppsChannel became active
    public var lastExternalApp: NSRunningApplication?

    private var pollTimer: Timer?
    private var lastChangeCount: Int = -1
    private var isInternalPasteAction: Bool = false
    private var saveTask: Task<Void, Never>?

    private let storage = ClipboardStorageService.shared

    private let pausedKey = "AppsChannelClipboard_Paused"
    private let excludeSensitiveKey = "AppsChannelClipboard_ExcludeSensitive"
    private let retentionKey = "AppsChannelClipboard_Retention"
    private let maxItemsKey = "AppsChannelClipboard_MaxItems"

    // Sensitive Pasteboard Types
    private static let sensitiveTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.bitwarden.client"),
        NSPasteboard.PasteboardType("de.keepassx.keepassxc"),
        NSPasteboard.PasteboardType("TransientType")
    ]

    private init() {
        if UserDefaults.standard.object(forKey: pausedKey) != nil {
            self.isPaused = UserDefaults.standard.bool(forKey: pausedKey)
        }
        if UserDefaults.standard.object(forKey: excludeSensitiveKey) != nil {
            self.excludeSensitive = UserDefaults.standard.bool(forKey: excludeSensitiveKey)
        }
        if let retentionRaw = UserDefaults.standard.string(forKey: retentionKey),
           let ret = ClipboardRetentionDuration(rawValue: retentionRaw) {
            self.retentionDuration = ret
        }
        if UserDefaults.standard.object(forKey: maxItemsKey) != nil {
            self.maxItemsCount = UserDefaults.standard.integer(forKey: maxItemsKey)
        }

        self.items = storage.loadItems()
        self.lastChangeCount = NSPasteboard.general.changeCount

        pruneAndSave()
        setupAppSwitchObserver()
        startPolling()
    }

    // MARK: - Polling
    public func startPolling() {
        stopPolling()
        pollTimer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkForPasteboardChanges()
            }
        }
    }

    public func stopPolling() {
        pollTimer?.invalidate()
        pollTimer = nil
    }

    private func setupAppSwitchObserver() {
        NSWorkspace.shared.notificationCenter.addObserver(
            forName: NSWorkspace.didActivateApplicationNotification,
            object: nil,
            queue: .main
        ) { [weak self] notification in
            guard let app = notification.userInfo?[NSWorkspace.applicationUserInfoKey] as? NSRunningApplication else { return }
            if app.bundleIdentifier != Bundle.main.bundleIdentifier {
                self?.lastExternalApp = app
            }
        }
    }

    // MARK: - Change Detection
    public func checkForPasteboardChanges() {
        guard !isPaused else { return }
        let pasteboard = NSPasteboard.general
        let currentChangeCount = pasteboard.changeCount

        guard currentChangeCount != lastChangeCount else { return }
        lastChangeCount = currentChangeCount

        guard !isInternalPasteAction else { return }

        // Check for sensitive types
        let types = pasteboard.types ?? []
        let hasSensitiveType = types.contains { pasteboardType in
            Self.sensitiveTypes.contains(pasteboardType)
        }

        if hasSensitiveType && excludeSensitive {
            return
        }

        let frontApp = lastExternalApp ?? NSWorkspace.shared.frontmostApplication
        let sourceAppName = frontApp?.localizedName
        let sourceAppBundleId = frontApp?.bundleIdentifier

        // 1. Check for Image clippings
        if pasteboard.canReadItem(withDataConformingToTypes: [NSPasteboard.PasteboardType.tiff.rawValue, NSPasteboard.PasteboardType.png.rawValue]) {
            if let image = NSImage(pasteboard: pasteboard),
               let tiffData = image.tiffRepresentation,
               let bitmap = NSBitmapImageRep(data: tiffData),
               let pngData = bitmap.representation(using: .png, properties: [:]) {

                // Save image to disk
                if let filename = storage.saveImage(data: pngData) {
                    let item = ClipboardItem(
                        type: .image,
                        textContent: nil,
                        previewText: "Image Clipping (\(Int(image.size.width)) × \(Int(image.size.height)))",
                        imageFilename: filename,
                        sourceAppName: sourceAppName,
                        sourceAppBundleId: sourceAppBundleId,
                        isConcealed: hasSensitiveType
                    )
                    addItem(item)
                    return
                }
            }
        }

        // 2. Check for File URLs
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL], !urls.isEmpty {
            let filePaths = urls.compactMap { $0.isFileURL ? $0.path : nil }
            if !filePaths.isEmpty {
                let filenames = filePaths.map { URL(fileURLWithPath: $0).lastPathComponent }.joined(separator: ", ")
                let item = ClipboardItem(
                    type: .file,
                    textContent: filePaths.joined(separator: "\n"),
                    previewText: filenames,
                    filePaths: filePaths,
                    sourceAppName: sourceAppName,
                    sourceAppBundleId: sourceAppBundleId,
                    isConcealed: hasSensitiveType
                )
                addItem(item)
                return
            }
        }

        // 3. Check for Strings
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            // Avoid duplicates of the most recent item
            if let topItem = items.first, topItem.textContent == string {
                return
            }

            let detection = ClipboardItem.detectType(text: string)
            let item = ClipboardItem(
                type: detection.type,
                textContent: string,
                colorHex: detection.colorHex,
                sourceAppName: sourceAppName,
                sourceAppBundleId: sourceAppBundleId,
                isConcealed: hasSensitiveType
            )
            addItem(item)
        }
    }

    private func addItem(_ item: ClipboardItem) {
        items.insert(item, at: 0)
        pruneAndSave()
        SoundEffectsManager.shared.playAction()
    }

    // MARK: - Actions
    public func copyToPasteboard(_ item: ClipboardItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        isInternalPasteAction = true
        defer {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.1) { [weak self] in
                self?.lastChangeCount = pasteboard.changeCount
                self?.isInternalPasteAction = false
            }
        }

        switch item.type {
        case .image:
            if let filename = item.imageFilename, let image = storage.loadImage(filename: filename) {
                pasteboard.writeObjects([image])
            }
        case .file:
            if let paths = item.filePaths {
                let urls = paths.map { NSURL(fileURLWithPath: $0) }
                pasteboard.writeObjects(urls)
            } else if let text = item.textContent {
                pasteboard.setString(text, forType: .string)
            }
        default:
            if let text = item.textContent {
                pasteboard.setString(text, forType: .string)
            }
        }
    }

    public func pasteToFrontmostApp(_ item: ClipboardItem) {
        AppUsageTracker.shared.recordUsage(
            id: "clipboard://paste",
            name: "Clipboard Paste",
            kind: .clipboard
        )
        copyToPasteboard(item)

        // Activate previous external app
        if let targetApp = lastExternalApp {
            targetApp.activate(options: [.activateIgnoringOtherApps])
        }

        // Simulate Command+V via Quartz Event Services
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            let src = CGEventSource(stateID: .combinedSessionState)
            let vKeyCode: CGKeyCode = 9 // Virtual key code for 'V'

            let keyDown = CGEvent(keyboardEventSource: src, virtualKey: vKeyCode, keyDown: true)
            keyDown?.flags = .maskCommand
            keyDown?.post(tap: .cghidEventTap)

            let keyUp = CGEvent(keyboardEventSource: src, virtualKey: vKeyCode, keyDown: false)
            keyUp?.flags = .maskCommand
            keyUp?.post(tap: .cghidEventTap)
        }
    }

    public func togglePin(_ item: ClipboardItem) {
        if let idx = items.firstIndex(where: { $0.id == item.id }) {
            items[idx].isPinned.toggle()
            SoundEffectsManager.shared.playAction()
        }
    }

    public func deleteItem(_ item: ClipboardItem) {
        if let filename = item.imageFilename {
            storage.deleteImage(filename: filename)
        }
        items.removeAll(where: { $0.id == item.id })
        SoundEffectsManager.shared.playAction()
    }

    public func clearAllHistory(preservePinned: Bool = true) {
        items = storage.clearAllHistory(items: items, preservePinned: preservePinned)
        SoundEffectsManager.shared.playAction()
    }

    public func pruneAndSave() {
        items = storage.pruneItems(items, retention: retentionDuration, maxItems: maxItemsCount)
        storage.saveItems(items)
    }

    private func scheduleSave() {
        saveTask?.cancel()
        saveTask = Task { [weak self] in
            try? await Task.sleep(nanoseconds: 300_000_000)
            guard !Task.isCancelled else { return }
            guard let self = self else { return }
            self.storage.saveItems(self.items)
        }
    }
}
